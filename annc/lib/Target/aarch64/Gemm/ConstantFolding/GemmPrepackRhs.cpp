extern "C" {
void annc_aarch64_sve_packb_f32(const float *rhs, float *packed, int32_t kSize,
                                int32_t nSize, int32_t ldb);
int64_t annc_aarch64_sve_packed_b_elements_f32(int64_t k, int64_t n);
void annc_aarch64_neon_packb_f32(const float *rhs, float *packed, int32_t kSize,
                                 int32_t nSize, int32_t ldb);
}

std::vector<float> packGemmLayout(
    const float *rhs, int64_t k, int64_t n,
    const aarch64::gemm::GemmTuningConfig &config) {
  using namespace aarch64::gemm;
  const bool isSve = config.isa == GemmIsa::kSve;
  auto elements = [&](int64_t kSize, int64_t nSize) {
    return isSve ? annc_aarch64_sve_packed_b_elements_f32(kSize, nSize)
                 : kSize * ((nSize + 3) / 4) * 4;
  };
  const std::vector<CacheBlock2D> blocks =
      partitionCache2D(k, n, config.cacheTile.kc, config.cacheTile.nc);
  int64_t total = 0;
  for (const CacheBlock2D &block : blocks)
    total += elements(block.kSize, block.nSize);
  std::vector<float> packed(total, 0.0f);
  int64_t offset = 0;
  for (const CacheBlock2D &block : blocks) {
    const float *source = rhs + block.kStart * n + block.nStart;
    const int32_t kSize = static_cast<int32_t>(block.kSize);
    const int32_t nSize = static_cast<int32_t>(block.nSize);
    const int32_t ldb = static_cast<int32_t>(n);
    if (isSve)
      annc_aarch64_sve_packb_f32(source, packed.data() + offset, kSize, nSize,
                                 ldb);
    else
      annc_aarch64_neon_packb_f32(source, packed.data() + offset, kSize, nSize,
                                  ldb);
    offset += elements(block.kSize, block.nSize);
  }
  return packed;
}

llvm::Error writePackedDataFile(llvm::StringRef path,
                                llvm::ArrayRef<std::pair<llvm::StringRef,
                                                         llvm::ArrayRef<float>>>
                                    entries) {
  std::error_code error;
  llvm::raw_fd_ostream output(path, error);
  if (error)
    return llvm::createStringError(error, "cannot create packed-data file '%s'",
                                   path.str().c_str());
  output << "// Auto-generated by aarch64-gemm-prepack-rhs. Do not edit.\n\n";
  char buffer[32];
  for (const auto &entry : entries) {
    output << "__attribute__((visibility(\"default\"), aligned(64))) const "
              "float "
           << entry.first << "[] = {\n";
    for (size_t i = 0; i < entry.second.size(); ++i) {
      std::snprintf(buffer, sizeof(buffer), "%a", entry.second[i]);
      output << "  " << buffer << (i + 1 < entry.second.size() ? ",\n" : "\n");
    }
    output << "};\n\n";
  }
  return llvm::Error::success();
}

// The contract records the candidate fields that determine the packed-B
// layout; aarch64-finalize-gemm-plan rejects a plan whose candidate drifted.
DictionaryAttr buildPrepackedContract(
    OpBuilder &builder, const aarch64::gemm::GemmTuningConfig &tuning,
    int64_t k, int64_t n, llvm::StringRef dataSymbol, size_t dataElements) {
  using namespace aarch64::gemm;
  NamedAttrList contract;
  contract.append("version", builder.getI64IntegerAttr(kPrepackedRhsVersion));
  contract.append("k", builder.getI64IntegerAttr(k));
  contract.append("n", builder.getI64IntegerAttr(n));
  contract.append("nc", builder.getI64IntegerAttr(tuning.cacheTile.nc));
  contract.append("kc", builder.getI64IntegerAttr(tuning.cacheTile.kc));
  contract.append("data_symbol", builder.getStringAttr(dataSymbol));
  contract.append("data_elements",
                  builder.getI64IntegerAttr(static_cast<int64_t>(dataElements)));
  return contract.getDictionary(builder.getContext());
}

struct AArch64GemmPrepackRhsPass
    : public AArch64GemmPrepackRhsBase<AArch64GemmPrepackRhsPass> {
  using Base::Base;

  explicit AArch64GemmPrepackRhsPass(llvm::StringRef path,
                                     llvm::StringRef inputs)
      : Base() {
    packedCPath = path.str();
    jitInputsPath = inputs.str();
  }

  void runOnOperation() override {
    ModuleOp module = getOperation();
    if (!jitInputsPath.empty()) {
      if (failed(prepareJitRhs(module, jitInputsPath, packedCPath)))
        signalPassFailure();
      return;
    }

    constant_folding::RhsDataLoader rhsLoader;
    struct PendingPack {
      std::string dataSymbol;
      std::vector<float> data;
      Operation *target;
      DictionaryAttr contract;
    };
    std::vector<PendingPack> pendingPacks;
    bool packingFailed = false;

    OpBuilder builder(module.getContext());
    module.walk([&](func::FuncOp func) {
      SmallVector<Operation *> gemms;
      func.walk([&](Operation *op) {
        if (aarch64::gemm::isGemmAnchor(op)) gemms.push_back(op);
      });
      for (auto [ordinal, gemm] : llvm::enumerate(gemms)) {
        if (!gemm->hasAttr(aarch64::gemm::kCandidateAttrName)) continue;
        auto candidate = aarch64::gemm::readCandidate(gemm);
        if (failed(candidate)) {
          packingFailed = true;
          continue;
        }
        if (candidate->strategy.rhsPacking !=
            aarch64::gemm::RhsPacking::kPrepacked)
          continue;

        auto rhsTy = dyn_cast<MemRefType>(
            aarch64::gemm::getGemmInput(gemm, 1).getType());
        if (!rhsTy || rhsTy.getRank() != 2 || !rhsTy.hasStaticShape() ||
            !rhsTy.getElementType().isF32())
          continue;
        const int64_t k = rhsTy.getShape()[0];
        const int64_t n = rhsTy.getShape()[1];
        if (k <= 0 || n <= 0) {
          gemm->emitOpError("has incompatible static GEMM operand shapes");
          packingFailed = true;
          continue;
        }

        std::vector<uint8_t> rawData;
        auto rhsName =
            gemm->getAttrOfType<StringAttr>(aarch64::gemm::kRhsNameAttrName);
        if (!rhsName || !rhsLoader.load(rhsName.getValue().str(), rawData)) {
          gemm->emitOpError("cannot load prepacked RHS checkpoint data");
          packingFailed = true;
          continue;
        }
        const uint64_t rhsElements =
            static_cast<uint64_t>(k) * static_cast<uint64_t>(n);
        if (rawData.size() != rhsElements * sizeof(float)) continue;
        std::vector<float> rhsData(static_cast<size_t>(rhsElements));
        std::memcpy(rhsData.data(), rawData.data(), rawData.size());
        const aarch64::gemm::GemmTuningConfig tuning{
            candidate->strategy.target, candidate->strategy.isa,
            candidate->strategy.dataType, candidate->strategy.cacheTile,
            candidate->strategy.kernelTile};
        std::vector<float> packed = packGemmLayout(rhsData.data(), k, n, tuning);
        if (packed.empty()) continue;

        std::string dataSymbol = "packed_" + func.getName().str();
        if (gemms.size() > 1)
          dataSymbol += "_matmul_" + std::to_string(ordinal);

        DictionaryAttr contract = buildPrepackedContract(
            builder, tuning, k, n, dataSymbol, packed.size());
        Operation *target = gemm;
        if (auto existing = target->getAttrOfType<DictionaryAttr>(
                aarch64::gemm::kPrepackedRhsAttrName);
            existing && existing != contract) {
          target->emitOpError("already has a different prepacked RHS contract");
          packingFailed = true;
          continue;
        }
        pendingPacks.push_back(
            {std::move(dataSymbol), std::move(packed), target, contract});
      }
    });

    if (packingFailed) {
      signalPassFailure();
      return;
    }
    if (pendingPacks.empty()) {
      module.emitWarning("aarch64-gemm-prepack-rhs: no GEMM packed");
      return;
    }

    std::string packedC = packedCPath;
    if (packedC.empty()) {
      if (const char *environment = std::getenv("ANNC_DEMO_PACKED_C"))
        packedC = environment;
    }
    if (packedC.empty()) {
      module.emitError("aarch64-gemm-prepack-rhs packed RHS data but "
                       "--packed-c and ANNC_DEMO_PACKED_C are not set");
      signalPassFailure();
      return;
    }
    SmallVector<std::pair<llvm::StringRef, llvm::ArrayRef<float>>> entries;
    for (const PendingPack &entry : pendingPacks)
      entries.push_back({entry.dataSymbol, entry.data});
    if (llvm::Error error = writePackedDataFile(packedC, entries)) {
      module.emitError() << "aarch64-gemm-prepack-rhs "
                         << llvm::toString(std::move(error));
      signalPassFailure();
      return;
    }
    for (const PendingPack &entry : pendingPacks)
      entry.target->setDiscardableAttr(aarch64::gemm::kPrepackedRhsAttrName,
                                       entry.contract);
  }
};

